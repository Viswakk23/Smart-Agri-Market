export function generateBuyerCSV(): string {
  const headers = ['id', 'buyer_name', 'company', 'category', 'location', 'state', 'crop', 'variety', 'demand_qty_qtl', 'target_price', 'payment_terms', 'verified', 'rating', 'gstin', 'fssai'];
  const rows = RAW_BUYER_REQUIREMENTS.map(b => 
    [
      b.id, 
      `"${b.buyerName}"`, 
      `"${b.company}"`, 
      `"${b.category}"`, 
      `"${b.location}"`, 
      `"${b.state}"`, 
      `"${b.crop}"`, 
      `"${b.variety}"`, 
      b.demandQty, 
      b.targetPrice, 
      `"${b.paymentTerms}"`, 
      b.verified, 
      b.rating,
      `"${b.verificationDetails?.gstinNumber || ''}"`,
      `"${b.verificationDetails?.fssaiNumber || ''}"`
    ].join(',')
  );
  return [headers.join(','), ...rows].join('\n');
}
